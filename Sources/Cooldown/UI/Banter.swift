        L("Ночная смена? Не забудьте про воду и плечи."),
        L("Лучшие идеи часто приходят утром. Проверим?"),
        L("Агенты не устают, а вы — да. Может, на сегодня всё?"),
        L("Ночью код пишется легко, а читается утром тяжело."),
        L("Тишина, темнота и вы. Не засиживайтесь."),
        L("Завтрашний вы скажет спасибо за сон."),
        L("Звёзды на месте, лимит тоже. Можно и отдохнуть."),
    ] }

    static var exhausted: [String] { [
