        L("Можно разобрать почту или просто посмотреть в окно."),
        L("Лимит кончился, а идеи — нет. Запишите их на потом."),
        L("Потянитесь, разомните шею — агент подождёт."),
        L("Перерыв по расписанию. Не вашему, но всё же."),
    ] }

    static var idle: [String] { [
