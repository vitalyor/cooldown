        L("Агенты ждут, когда вы вернётесь."),
        L("Всё спокойно — можно выдохнуть."),
        L("Лимит свежий, как утренний кофе."),
        L("Ничего не происходит — и это нормально."),
        L("Запас на месте. Начнём что-нибудь интересное?"),
        L("Агенты скучают без дела."),
        L("Полный бак и пустая дорога."),
        L("Хорошее время для большой задачи."),
        L("Тихо. Даже подозрительно тихо."),
    ] }

    static var lasts: [String] { [
        L("Можно не экономить — работайте в удовольствие."),
        L("Запаса хватает, так держать."),
        L("Темп отличный, лимит не подведёт."),
        L("Идёте ровно, как по расписанию."),
        L("Хватает с запасом — можно замахнуться на большое."),
        L("Хороший ритм. Вы с агентом — отличная команда."),
        L("Лимит в надёжных руках."),
        L("Спокойно работаем, до сброса дотянем."),
        L("Можно смело браться за следующее."),
