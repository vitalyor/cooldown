import Foundation

/// A friendly word under the forecast, so the numbers read like a colleague talking, not a meter.
/// The phrase stays the same for the whole window, so it never flickers; each next window takes
/// the next phrase of its mood, so one comes back only after the whole set has been seen.
enum Banter {
    static func line(_ outcome: Forecast.Outcome, window: LimitWindow, now: Date) -> String {
        let pool = phrases(outcome, remaining: window.remainingPercent, hour: Calendar.current.component(.hour, from: now))
        // Consecutive 5-hour windows give consecutive numbers: the set is walked in order.
        let turn = Int(window.resetsAt.timeIntervalSince1970 / 18_000)
        return pool[((turn % pool.count) + pool.count) % pool.count]
    }

    static func phrases(_ outcome: Forecast.Outcome, remaining: Double, hour: Int) -> [String] {
        if (1...5).contains(hour) { return night }
        switch outcome {
        case .exhausted: return exhausted
        case .idle: return idle
        case .lasts: return lasts
        case .runsOut where remaining <= 25: return almostOut
        case .runsOut: return fast
        }
    }

